uint8_t kit_sht_read(int16_t* t10, uint16_t* rh10) {
	uint32_t now = hal_millis();

	*t10 = (int16_t)(265 + ui_sin((uint8_t)(now / 700)) * 9 / 127 + ui_sin((uint8_t)(now / 130)) / 64);
	*rh10 = (uint16_t)(610 - ui_sin((uint8_t)(now / 900)) * 40 / 127);
	return 1;
}

