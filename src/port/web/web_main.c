/**
 ******************************************************************************
 * @brief:  The demo of the AK Base Kit in a web browser (WebAssembly).
 *
 *  What runs is the firmware itself: kernel, the sample app with its shell
 *  and Modbus slave, and the demo screens - the same sources as on the kit.
 *  Only the lowest layer differs: the host port (port/host) stands in for the
 *  chip, and this file stands in for the board (demo/kit.h): display, buttons,
 *  buzzer, clock, sensor and SPI flash become memory the page reads and writes.
 *
 *  The kernel never gets to run its endless loop here; the page calls
 *  web_tick() a hundred times a second and each call lets the kernel handle
 *  what became due (task_run_once).
 *
 *  Build: python port/web/build.py  (needs the Emscripten SDK)
 ******************************************************************************
**/

