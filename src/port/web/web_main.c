/* the clock of the computer; setting it on the kit only moves an offset */
uint8_t kit_rtc_get(uint8_t* hh, uint8_t* mm, uint8_t* ss) {
	time_t t = time(0) + rtc_offset_s;
	struct tm* tm = localtime(&t);

	*hh = (uint8_t)tm->tm_hour;
	*mm = (uint8_t)tm->tm_min;
	*ss = (uint8_t)tm->tm_sec;
	return 1;
}

uint8_t kit_rtc_set(uint8_t hh, uint8_t mm, uint8_t ss) {
	uint8_t h, m, s;

	kit_rtc_get(&h, &m, &s);
	rtc_offset_s += ((int32_t)hh - h) * 3600 + ((int32_t)mm - m) * 60 + ((int32_t)ss - s);
	return 1;
}

/* no sensor in a browser: a slow wave, so the graph has something to draw */
