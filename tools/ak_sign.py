#!/usr/bin/env python3
"""
ak_sign.py - keys for signed firmware images (ECDSA P-256 / SHA-256).

  keygen   -o DIR          write DIR/priv.pem (keep it off the repository!)
                           and DIR/pub.pem
  pubkey-c --pub PEM -o C  write the C file that puts the public key into the
                           bootloader and app: src/services/fw/fw_pubkey.c
  verify   IMG --pub PEM   check the signature of an .img

Signing an image is done by mkimage.py (patch / build / synthetic ...
--sign-key priv.pem). Needs the 'cryptography' package: pip install cryptography.

The signed data is SHA-256 over the first 48 header bytes (magic .. board,
sig_type) followed by the binary; the signature is raw r || s (64 bytes) at
header offset 48. See src/services/fw/fw_sign.h.
"""

import argparse
import hashlib
import os
import sys

HDR_SIZE = 256
SIGN_HDR_LEN = 48
SIG_OFF = 48
SIG_TYPE_OFF = 44
SIG_ECDSA_P256 = 1


def _crypto():
    try:
        from cryptography.hazmat.primitives import hashes, serialization
        from cryptography.hazmat.primitives.asymmetric import ec, utils
    except ImportError:
        raise SystemExit("the 'cryptography' package is needed: pip install cryptography")
    return hashes, serialization, ec, utils


def load_private(path):
    _, serialization, ec, _ = _crypto()
    k = serialization.load_pem_private_key(open(path, "rb").read(), password=None)
    if not isinstance(k, ec.EllipticCurvePrivateKey) or k.curve.name != "secp256r1":
        raise SystemExit("%s: not a P-256 private key" % path)
    return k


def load_public(path):
    _, serialization, ec, _ = _crypto()
    k = serialization.load_pem_public_key(open(path, "rb").read())
    if not isinstance(k, ec.EllipticCurvePublicKey) or k.curve.name != "secp256r1":
        raise SystemExit("%s: not a P-256 public key" % path)
    return k


def public_raw(pub):
    n = pub.public_numbers()
    return n.x.to_bytes(32, "big") + n.y.to_bytes(32, "big")


def image_hash(blob):
    """SHA-256 over the signed part of an image (header[0:48] + binary)."""
    return hashlib.sha256(blob[:SIGN_HDR_LEN] + blob[HDR_SIZE:]).digest()


def sign_blob(hdr, img, priv):
    """hdr: 252 header bytes without CRC, sig_type already set. Returns the
    header with the raw signature filled in (still without CRC)."""
    hashes, _, ec, utils = _crypto()
    h = hashlib.sha256(hdr[:SIGN_HDR_LEN] + img).digest()
    der = priv.sign(h, ec.ECDSA(utils.Prehashed(hashes.SHA256())))
    r, s = utils.decode_dss_signature(der)
    sig = r.to_bytes(32, "big") + s.to_bytes(32, "big")
    return hdr[:SIG_OFF] + sig + hdr[SIG_OFF + 64:]


def verify_blob(blob, pub):
    """True if the image carries a valid ECDSA P-256 signature for pub."""
    hashes, _, ec, utils = _crypto()
    from cryptography.exceptions import InvalidSignature
    if blob[SIG_TYPE_OFF] != SIG_ECDSA_P256:
        return False
    sig = blob[SIG_OFF:SIG_OFF + 64]
    der = utils.encode_dss_signature(int.from_bytes(sig[:32], "big"), int.from_bytes(sig[32:], "big"))
    try:
        pub.verify(der, image_hash(blob), ec.ECDSA(utils.Prehashed(hashes.SHA256())))
        return True
    except InvalidSignature:
        return False


def cmd_keygen(a):
    _, serialization, ec, _ = _crypto()
    os.makedirs(a.out, exist_ok=True)
    priv_path = os.path.join(a.out, "priv.pem")
    pub_path = os.path.join(a.out, "pub.pem")
    if os.path.exists(priv_path) and not a.force:
        raise SystemExit("%s exists (use --force to overwrite)" % priv_path)
    k = ec.generate_private_key(ec.SECP256R1())
    open(priv_path, "wb").write(k.private_bytes(serialization.Encoding.PEM,
                                                serialization.PrivateFormat.PKCS8,
                                                serialization.NoEncryption()))
    open(pub_path, "wb").write(k.public_key().public_bytes(serialization.Encoding.PEM,
                                                           serialization.PublicFormat.SubjectPublicKeyInfo))
    print("wrote %s (keep it secret) and %s" % (priv_path, pub_path))


def cmd_pubkey_c(a):
    raw = public_raw(load_public(a.pub))
    lines = ["/**",
             " * Public key that signed images must match (FW_IMAGE_SIGN=1).",
             " * Generated by tools/ak_sign.py pubkey-c from %s" % os.path.basename(a.pub),
             " */",
             '#include "fw_sign.h"', "",
             "const uint8_t fw_sign_pubkey[64] = {"]
    for part, name in ((raw[:32], "X"), (raw[32:], "Y")):
        lines.append("\t/* %s */" % name)
        for i in range(0, 32, 16):
            lines.append("\t" + " ".join("0x%02x," % b for b in part[i:i + 16]))
    lines += ["};", ""]
    open(a.output, "w").write("\n".join(lines))
    print("wrote %s" % a.output)


def cmd_verify(a):
    blob = open(a.image, "rb").read()
    ok = verify_blob(blob, load_public(a.pub))
    print("%s: %s" % (a.image, "signature OK" if ok else "BAD or missing signature"))
    return 0 if ok else 1


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("keygen")
    s.add_argument("-o", "--out", required=True, help="directory for priv.pem and pub.pem")
    s.add_argument("--force", action="store_true")
    s.set_defaults(fn=cmd_keygen)
    s = sub.add_parser("pubkey-c")
    s.add_argument("--pub", required=True)
    s.add_argument("-o", "--output", required=True)
    s.set_defaults(fn=cmd_pubkey_c)
    s = sub.add_parser("verify")
    s.add_argument("image")
    s.add_argument("--pub", required=True)
    s.set_defaults(fn=cmd_verify)
    a = p.parse_args(argv)
    return a.fn(a) or 0


if __name__ == "__main__":
    sys.exit(main())
